import UIKit

/// يولّد باركود CODE128-B بصيغة مطابقة لـ JsBarcode في الويب (يُستخدم لرابط الفاتورة).
enum Code128Barcode {
    // أنماط الرموز: القيمة ← سلسلة من '1' (قضيب) و'0' (فراغ)، كل رمز 11 وحدات.
    static let patterns: [String] = [
        "11011001100","11001101100","11001100110","10010011000","10010001100",
        "10001001100","10011001000","10011000100","10001100100","11001001000",
        "11001000100","11000100100","10110011100","10011011100","10011001110",
        "10111001100","10011101100","10011100110","11001110010","11001011100",
        "11001001110","11011100100","11001110100","11101101110","11101001100",
        "11100101100","11100100110","11101100100","11100110100","11100110010",
        "11011011000","11011000110","11000110110","10100011000","10001011000",
        "10001000110","10110001000","10001101000","10001100010","11010001000",
        "11000101000","11000100010","10110111000","10110001110","10001101110",
        "10111011000","10111000110","10001110110","11101110110","11010001110",
        "11000101110","11011101000","11011100010","11011101110","11101011000",
        "11101000110","11100010110","11101101000","11101100010","11100011010",
        "11101111010","11001000010","11110001010","10100110000","10100001100",
        "10010110000","10010000110","10000101100","10000100110","10110010000",
        "10110000100","10011010000","10011000010","10000110100","10000110010",
        "11000010010","11001010000","11110111010","11000010100","10001111010",
        "10100111100","10010111100","10010011110","10111100100","10011110100",
        "10011110010","11110100100","11110010100","11110010010","11011011110",
        "11011110110","11110110110","10101111000","10100011110","10001011110",
        "10111101000","10111100010","11110101000","11110100010","10111011110",
        "10111101110","11101011110","11110101110", // 102
        "11010000100", // 103 Code A
        "11010010000", // 104 Code B (Start)
        "11010011100", // 105 Code C
        "1100011101011" // 106 Stop (13 modules)
    ]

    static let startCodeB = 104
    static let stopValue = 106

    /// يولّد صورة باركود من نص (رابط)، تُرجع UIImage مع مناطق هامشية.
    static func image(for text: String, height: CGFloat = 80) -> UIImage? {
        var symbols: [Int] = [startCodeB]
        for ch in text.unicodeScalars {
            let a = Int(ch.value)
            guard a >= 32 else { return nil }
            symbols.append(a &- 32) // CODE128B: القيمة = ascii - 32
        }
        guard symbols.count > 1 else { return nil }

        // رمز المجموع الاختباري
        var checksum = startCodeB
        for (i, s) in symbols.enumerated() where i > 0 {
            checksum += s * i
        }
        symbols.append(checksum % 103)
        symbols.append(stopValue)

        // وحّد أطوال أنماط القضبان/الفراغات إلى سلسلة ثنائية
        let bits = symbols.map { patterns[$0] }.joined()

        let module: CGFloat = 1.2
        let quiet: CGFloat = 10
        let width = CGFloat(bits.count) * module + quiet * 2
        let renderer = UIGraphicsImageRenderer(size: CGSize(width: width, height: height))
        let image = renderer.image { ctx in
            let cg = ctx.cgContext
            cg.setFillColor(UIColor.white.cgColor)
            cg.fill(CGRect(x: 0, y: 0, width: width, height: height))
            cg.setFillColor(UIColor.black.cgColor)
            var x = quiet
            for b in bits {
                if b == "1" {
                    cg.fill(CGRect(x: x, y: 0, width: module, height: height))
                }
                x += module
            }
        }
        return image
    }
}
